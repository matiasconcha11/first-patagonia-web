  /* ---------- Nav link map (href → translation key) ---------- */
  var NAV_MAP = {
    'lodge.html':            'nav.lodge',
    'actividades.html':      'nav.act',
    'programas.html':        'nav.prog',
    'paso-vuriloche.html':   'nav.paso',
    'espiritupionero.html':  'nav.pioneer',
    'planifica.html':        'nav.plan',
  };

  /* ---------- Apply language ---------- */
  function applyLang(lang) {
    var dict = T[lang];
    if (!dict) return;

    // data-i18n → textContent
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) el.textContent = dict[key];
    });

    // data-i18n-html → innerHTML (for elements with <br>/<em>)
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });

    // Nav links (by href)
    Object.keys(NAV_MAP).forEach(function (href) {
      var key = NAV_MAP[href];
      document.querySelectorAll('a[href="' + href + '"]').forEach(function (a) {
        // Only update nav links (not footer links that have longer text)
        if (a.closest('.nav__links') && dict[key]) {
          a.textContent = dict[key];
        }
      });
    });

    // "Reservar" nav CTA (has class nav__cta)
    var navCta = document.querySelector('.nav__cta');
    if (navCta && dict['nav.book']) navCta.textContent = dict['nav.book'];

    // Audio label
    var audioLabel = document.querySelector('.audio-label');
    if (audioLabel && dict['audio.label']) audioLabel.textContent = dict['audio.label'];

    // Update html lang attribute
    document.documentElement.lang = lang;

    // Mark active button
    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      btn.classList.toggle('lang-btn--active', btn.dataset.lang === lang);
    });

    // Save preference
    localStorage.setItem('fp_lang', lang);
  }

  /* ---------- Inject language switcher into nav ---------- */
  function injectSwitcher() {
    var navLinks = document.getElementById('navLinks');
    if (!navLinks) return;

    var switcher = document.createElement('li');
    switcher.className = 'lang-switcher';
    switcher.innerHTML =
      '<button class="lang-btn" data-lang="es">ES</button>' +
      '<button class="lang-btn" data-lang="en">EN</button>' +
      '<button class="lang-btn" data-lang="de">DE</button>';
    navLinks.appendChild(switcher);

    switcher.querySelectorAll('.lang-btn').forEach(function (btn) {
      btn.addEventListener('click', function () {
        applyLang(btn.dataset.lang);
      });
    });
  }

  /* ---------- Init ---------- */
  function init() {
    injectSwitcher();
    var saved = localStorage.getItem('fp_lang') || 'es';
    applyLang(saved);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }

